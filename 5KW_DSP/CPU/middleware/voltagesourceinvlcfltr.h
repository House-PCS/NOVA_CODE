inline void detectZeroCrossingClearPWMTrip(void)
{
    if((invSinePrev<=(float)(0.00))&&(invSine>(float)(0.00)))
        zeroCrossDetectFlag=1;
    else
        zeroCrossDetectFlag=0;

    if (clearInvTrip==1 && zeroCrossDetectFlag==1)
    {
        // clear all the configured trip sources for the PWM module
        EALLOW;
        //EPwm2Regs.AQCSFRC.bit.CSFA=1; // continous low
        EPwm1Regs.TZCLR.bit.OST=0x1;
        EPwm2Regs.TZCLR.bit.OST=0x1;
        EPwm1Regs.TZCLR.bit.CBC=0x1;
        EPwm2Regs.TZCLR.bit.CBC=0x1;
        EPwm1Regs.TZCLR.bit.DCAEVT1=0x1;
        EPwm2Regs.TZCLR.bit.DCAEVT1=0x1;
        EDIS;

        clearInvTrip=0;
        closeILoopInv=1;
    }

    if(invSinePrev < -0.95 && invSine > -0.95)
    {
        if(rlyConnect==1)
        {
//          closeRelay();
        }
    }

    if (rlyConnect==0)
    {
//      openRelay();
    }

    invSinePrev=invSine;

}

