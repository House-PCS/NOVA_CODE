inline void ClearInterrupt(void)
{
    EPwm2Regs.ETCLR.bit.INT=1;
    PieCtrlRegs.PIEACK.all=PIEACK_GROUP3;
}

inline void setupInterrupt(void)
{
    EALLOW;
    //PWM1 INT is used to trigger the ISR
    PieVectTable.EPWM2_INT = &InverterISR;
    EPwm2Regs.ETSEL.bit.INTSEL = ET_CTR_ZERO;   // INT on Zero event
    EPwm2Regs.ETSEL.bit.INTEN = 1;              // Enable INT
    EPwm2Regs.ETPS.bit.INTPRD = CNTRL_ISR_FREQ_RATIO;         // Generate INT on every event
    ClearInterrupt();

    PieCtrlRegs.PIEIER3.bit.INTx2 = 1; // Enable PWM11INT in PIE group 3
    EPwm2Regs.ETCLR.bit.INT=1;

    IER |= M_INT3; //Enable group 3 interrupts

    // EINT;  // Enable Global interrupt INTM
    // ERTM;  // Enable Global realtime interrupt DBGM
    EDIS;
}

