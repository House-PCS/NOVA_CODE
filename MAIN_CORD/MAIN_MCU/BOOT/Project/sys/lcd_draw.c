void lcd_progress_bar(uint32_t process)
{
    int x = 0, y = 0;
	int x_process[2] = {140, 340};
	int y_process[2] = {155, 165};

	int tips[2] = {256, 64};

    DevLcdSetCursor(0, 0);
    DevLcdWriteRAMCmd();
    for(y = 0; y < 320; y++)
    {
        for(x = 0; x < 480; x++)
        {
			// 进度条边框
			if (x > x_process[0]-2 && x < x_process[1]+2)
			{
				if ((y > y_process[0]-2 && y < y_process[0]) 
					|| (y > y_process[1] && y < y_process[1]+2))
				{
					DevLcdWriteData(0x0F01);
					continue;
				}
			}

			if (y >= y_process[0] && y <= y_process[1] 
				&& (x == x_process[0]-1 || x == x_process[1]+1))
			{
				DevLcdWriteData(0x07eF);
				continue;
			}

#if 1
			// 进度条
			if (y > y_process[0] && y < y_process[1] 
				&& x > x_process[0] && x < x_process[1]
				&& x < x_process[0] + process)
			{
				DevLcdWriteData(0x07eF);
				continue;
			}
#endif 

			// 画点阵字
			if (x < tips[0] && y < tips[1])
			{

				int _x1 = (x/8) + y*tips[0]/8;
				int _x2 = 7 - x%8;
				int piexl = bitmap_bytes[_x1] >> _x2;
				piexl = piexl & 0x01;

				if (piexl != 0)
				{
					DevLcdWriteData(0x07eF);
					continue;
				}
			}
            DevLcdWriteData(0x000F);
        }
    }
}



