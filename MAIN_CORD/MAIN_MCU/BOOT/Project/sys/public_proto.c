/************************************************************************
@ Function Name: DataToUnshort
@ Description  : u8 to u16
@ Input    Para: Buf, Mode Flag
@ Output   Para: None
@ Return  Value: u16
@ Author   Data: Sophy & 2017.8.23
*************************************************************************/
uint16_t DataToUnshort(uint8_t *pBuffer, uint8_t uModeFlag)
{
    uint16_t uShort = 0;
    
    uShort = *pBuffer++;
    
    if(USING_MODE_BIG == uModeFlag)
    {
        /* 大端模式 */
        uShort = (uShort << 8) | (*pBuffer);
    }
    else
    {
        /* 小端模式 */
        uShort |= (*pBuffer) << 8;
    }

    return uShort;	
}

/************************************************************************
@ Function Name: DataToUnchar
@ Description  : u16 to u8
@ Input    Para: Buf, u16, Mode Flag
@ Output   Para: None
@ Return  Value: None
@ Author   Data: Sophy & 2017.8.23
*************************************************************************/
void DataToUnchar(uint8_t *pBuffer, uint16_t uShort, uint8_t uModeFlag)
{
    if(USING_MODE_BIG == uModeFlag)
    {
                  /* 大端模式 */
                  *pBuffer++ = (uShort >> 8) & 0xFF;
                  *pBuffer   = uShort & 0xFF;	
    }
    else
    {
                  /* 小端模式 */
                  *pBuffer = uShort & 0xFF;
                  pBuffer++;
                  *pBuffer   = (uShort >> 8) & 0xFF;
    }
}

/************************************************************************
@ Function Name: DataToUnint
@ Description  : u8 to u32
@ Input    Para: Buf, Mode Flag
@ Output   Para: None
@ Return  Value: u32
@ Author   Data: Sophy & 2017.8.23
*************************************************************************/
uint32_t DataToUnint(uint8_t *pBuffer, uint8_t uModeFlag)
{
    uint32_t uInt = 0;
    
    if(USING_MODE_BIG == uModeFlag)
    {
                  /* 大端模式 */
                  uInt = DataToUnshort(pBuffer, USING_MODE_BIG);
                  uInt <<= 16;
                  uInt |= DataToUnshort(pBuffer + 2, USING_MODE_BIG);
    }
    else
    {
                  /* 小端模式 */
                  uInt = DataToUnshort(pBuffer + 2, USING_MODE_SMALL);
                  uInt <<= 16;
                  uInt |= DataToUnshort(pBuffer, USING_MODE_SMALL);
    }

    return uInt;
}

