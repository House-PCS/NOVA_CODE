void DataModeChange(uint8_t *pBuffer, uint8_t *pData, uint8_t uModeFlag, uint8_t uLen)
{
    uint8_t  i;
    uint16_t uShort = 0;
    uint8_t  uIndex = 0;
  
    if((uLen % 2) != 0)
    {
          uLen++;
    }
    for(i = 0; i < (uLen >> 1); i++)
    {
          memmove(&uShort, &pData[uIndex], 2);
          DataToUnchar(&pBuffer[uIndex], uShort, uModeFlag);
          uIndex += 2;
    }
}
/************************************************************************
@ Function Name: CalCrcShort
@ Description  : Calculate CRC16
@ Input    Para: Frame, Len
@ Output   Para: None
@ Return  Value: Crc16
@ Author   Data: Sophy & 2017.8.23
*************************************************************************/
uint16_t CalCrcShort(uint8_t *pFrame, uint16_t uLen)
{
    uint8_t	        uCrcHigh  = 0xFF;
    uint8_t	        uCrcLow   = 0xFF;
    uint16_t	uIndex    = 0;
    uint16_t        uCrcShort = 0;

    while(uLen--)
    {
        uIndex   = uCrcLow ^ *(pFrame++);
        uCrcLow  = (uint8_t)(uCrcHigh ^ CRCHi[uIndex]);
        uCrcHigh = CRCLo[uIndex];
    }

    uCrcShort = (uint16_t)(uCrcHigh << 8 | uCrcLow);
    
    return uCrcShort;
}

/************************************************************************
@ Function Name: CalCrcValue
@ Description  : Calculate CRC32
@ Input    Para: Frame, Len
@ Output   Para: None
@ Return  Value: Crc32
@ Author   Data: Sophy & 2017.8.23
*************************************************************************/
uint32_t CalCrcValue(uint8_t *pFrame, uint32_t uLen)
{
#define CRCPOLY_BE 0x04c11db7

    uint32_t i;
    uint32_t uData   = 0;
    uint32_t uLength = 0;
    uint32_t uCrcCheck   = 0xFFFFFFFF;

    /* 校验长度是否是4的倍数不是补0xff */
    if((uLen % 4) != 0)
    {
            uLength = 4 - uLen % 4;
            for(i = 0; i < uLength; i++)
            {
                 pFrame[uLen + i] = 0xFF;
            }	
            uLen += uLength;
    }

    while(uLen > 0)
    {
            uData = (pFrame[0] & 0xFF) + (pFrame[1] << 8)  + (pFrame[2] << 16) + (pFrame[3] << 24);
            uCrcCheck ^= uData;
            pFrame += 4;
            uLen -= 4;

            for(i = 0; i < 32; i++)
            uCrcCheck = (uCrcCheck << 1) ^ ((uCrcCheck & 0x80000000) ? CRCPOLY_BE : 0);
    }

    return uCrcCheck;
}


