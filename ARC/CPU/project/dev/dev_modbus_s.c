static uint16_t _CrcModbus(uint8_t *p, uint16_t len)
{
    uint8_t ucCRCHi = 0xFF; /* 高CRC字节初始化 */
	uint8_t ucCRCLo = 0xFF; /* 低CRC 字节初始化 */
	uint16_t usIndex;  /* CRC循环中的索引 */
    while (len--)
    {
		usIndex = ucCRCLo ^ *p++; /* 计算CRC */
		ucCRCLo = ucCRCHi ^ _CrcHi[usIndex];
		ucCRCHi = _CrcLo[usIndex];
    }
    return ((uint16_t)ucCRCHi << 8 | ucCRCLo);
}



static bool _CrcJudge(uint8_t *p, uint16_t len)
{
    uint16_t calc_crc, act_crc;
    
    act_crc = (p[len - 1] << 8) | (p[len - 2]);
    calc_crc = _CrcModbus(p, len - 2);
    if(act_crc == calc_crc)
    {
        return true;
    }
    return false;
}

void DevModbusRTUInit()
{
    QueueInit(&gModbusMTURevQueue, MODBUS_RTU_REV_QUEUE_DEPTH, sizeof(ModbusRTURevData_t));
    for(uint8_t i = 0; i < MODBUS_RTU_REV_QUEUE_DEPTH; i++)
	{
		_gModbusData[i].pData = _RevData[i];
	}
    gUart1ModbusHandle.pRxBuf = _Uart1RxBuf;
    gUart1ModbusHandle.rx_size = MODBUS_RTU_RX_SIZE;
    gUart1ModbusHandle.irq_rx_process = _IrqRxProcess;
	gUart1ModbusHandle.dma_tx_complete_process = _DMATxCompleteIrqProcess;
    DevModbusSlaveBspInit();
}



static void _RevDataAnalysis(uint16_t len)
{
    static uint16_t rev_index = 0;
    uint8_t *p = gUart1ModbusHandle.pRxBuf;
    if(len < 5)
    {
        return;
    }
	if((*p == REQUST_PACKET_HEAD) && (*(p + 1) == SEND_ADDR) && \
       (*(p + 2) == RECV_ADDR))
    {
		_gModbusData[rev_index].data_type = UART_DATA_TYPE_UPGRADE;
	}
	else
	{
		if(MODBUS_DEVICE_ADDR  != p[0])//不是自己的包
		{
			return;
		}
		if(_CrcJudge(p, len) == false)
		{
			return;
		}
		_gModbusData[rev_index].data_type = UART_DATA_TYPE_NORMAL;
	}
    _gModbusData[rev_index].data_size = len;
    memcpy(_gModbusData[rev_index].pData, p, len);
    
    if(QueuePut(&gModbusMTURevQueue, &_gModbusData[rev_index]) == false)
    {
        return;
    }
    rev_index++;
    rev_index %= MODBUS_RTU_REV_QUEUE_DEPTH;
    
}



static void _IrqRxProcess()
{
    uint16_t rev_size = 0;
    
	/*DMA方式，空闲中断机制*/
	UartDMARxDisable(&gUart1ModbusHandle);
	rev_size = UartDMARxDataLength(&gUart1ModbusHandle);	
    _RevDataAnalysis(rev_size);      
	UartDMARxEnable(&gUart1ModbusHandle);
}



void ModbusRTUSend(uint8_t *p, uint16_t size)
{
	if(com_revupgradedata.is_update_data == true)
	{
		uint16_t crc;
		GpioBitSet(&gGpioDirModbusHandle);         /*提前打开RS485发送信号*/

		gUart1ModbusHandle.pTxBuf = p;            /*升级包中已经进行过校验，此处不需要*/
//		crc = _CrcModbus(p, size);
//		gUart1ModbusHandle.pTxBuf[size] = crc & 0xFF; 
//		gUart1ModbusHandle.pTxBuf[size + 1] = (crc >> 8) & 0xFF;

		gUart1ModbusHandle.tx_size = size;
		_gModbusSendCompleteFlag = 0;
		_gModbusSendTimeout = tim_get_systime();
		_gModbusSendMaxTime = 1000 * (8 + 4) * gUart1ModbusHandle.tx_size / gUart1ModbusHandle.uart_cfg->baud_rate + 2;//单位ms,8表示数据位时长，4表示起始+停止+GAP时长, +2表示增加一些冗余
		UartSend(&gUart1ModbusHandle); 
	}
	else
	{
		uint16_t crc;
		GpioBitSet(&gGpioDirModbusHandle);         /*提前打开RS485发送信号*/

		gUart1ModbusHandle.pTxBuf = p;
		crc = _CrcModbus(p, size);
		gUart1ModbusHandle.pTxBuf[size] = crc & 0xFF;
		gUart1ModbusHandle.pTxBuf[size + 1] = (crc >> 8) & 0xFF;

		gUart1ModbusHandle.tx_size = size + 2;
		_gModbusSendCompleteFlag = 0;
		_gModbusSendTimeout = tim_get_systime();
		_gModbusSendMaxTime = 1000 * (8 + 4) * gUart1ModbusHandle.tx_size / gUart1ModbusHandle.uart_cfg->baud_rate + 2;//单位ms,8表示数据位时长，4表示起始+停止+GAP时长, +2表示增加一些冗余
		UartSend(&gUart1ModbusHandle);  
	}
}

static void _DMATxCompleteIrqProcess()
{
    _gModbusSendCompleteFlag = 1;
    
}
bool DevModbusSendComplete()
{
    if(GpioBitGet(&gGpioDirModbusHandle) != 0)
    {
        return false;
    }
    else
    {
        return true;
    }
}
/*大轮询调用*/
void DevModbusDirCtlProcess()
{
    if(_gModbusSendCompleteFlag == 1)
    {
        if(UartSendCompleteFlag(&gUart1ModbusHandle) == true)/*串口寄存器已经发送完成，为空*/
        {
            GpioBitReset(&gGpioDirModbusHandle);   //拉低PA0，调整为接收
            _gModbusSendCompleteFlag = 0;
        }
        else
        {
            if((uint32_t)(tim_get_systime() - _gModbusSendTimeout) > _gModbusSendMaxTime)/*发送异常，恢复接收状态*/
            {
                GpioBitReset(&gGpioDirModbusHandle);
            }
        }
    }
    else/*处理超时*/
    {
        if(GpioBitGet(&gGpioDirModbusHandle) != 0)
        {
            if((uint32_t)(tim_get_systime() - _gModbusSendTimeout) > _gModbusSendMaxTime)/*发送超时，恢复接收状态*/
            {
                GpioBitReset(&gGpioDirModbusHandle);
            }
        }
    }
}


uint16_t BEBufToUint16(uint8_t *_pBuf)
{
    return (((uint16_t)_pBuf[0] << 8) | _pBuf[1]);
}

uint16_t BEBufToUint16ToBEBuf(uint8_t *_pBuf)
{
    return (((uint16_t)_pBuf[1] << 8) | _pBuf[0]);
}













