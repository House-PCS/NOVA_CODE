/** 
* @brief  CRC16_MODBUS校验算法
* @param  puchMsg：待校验数据缓存
* @param  usDataLen：待校验数据长度
* @return  unsigned short：CRC校验值
* @note:
*
*/
unsigned short Crc16_Modbus (unsigned char *puchMsg, unsigned short usDataLen)
{ 
    unsigned char uchCRCHi = 0xFF ; /* high byte of CRC initialized */ 
    unsigned char uchCRCLo = 0xFF ; /* low byte of CRC initialized */ 
    unsigned uIndex ; /* will index into CRC lookup table */ 
    
    while (usDataLen--) /* pass through message buffer */ 
    { 
        uIndex = uchCRCLo ^ *puchMsg++ ; /* calculate the CRC */ 
        uchCRCLo = uchCRCHi ^ auchCRCHi[uIndex] ; 
        uchCRCHi = auchCRCLo[uIndex] ; 
    } 
    return (uchCRCHi << 8 | uchCRCLo) ; 
}
/** 
* @brief  BCD转HEX格式
* @param  data：BCD格式数据
* @return  unsigned char：HEX数据
* @note:
*
*/
unsigned char bcd_to_hex(unsigned char data)
{
    unsigned char temp;

    temp = ((data>>4)*10 + (data&0x0f));
    return temp;
}
/** 
* @brief  HEX转BCD格式
* @param  data：HEX格式数据
* @return  unsigned char：BCD格式数据
* @note:
*
*/
unsigned char hex_to_bcd(unsigned char data)
{
    unsigned char temp;

    temp = (((data/10)<<4) + (data%10));
    return temp;
}
