/** 
* @brief  卡尔曼滤波算法
* @param  inData：原始数据
* @param  k_para：卡尔曼参数    
* @return  int：滤波后数据
* @note:
*
*/
int KalmanFilter(int inData,KalmanParaType* k_para)
{
//    static float  kalman = 0; //上次卡尔曼值(估计出的最优值)
//    static float  p = 10;
//    static float  q = 0.001; //q:过程噪声
//    static float  r = 0.001; //r:测量噪声
//    static float  kg = 0; //kg:卡尔曼增益
 
    k_para->p += k_para->q;
    k_para->kg = k_para->p / ( k_para->p + k_para->r ); //计算卡尔曼增益
    k_para->kalman = k_para->kalman + (k_para->kg * (inData - k_para->kalman)); //计算本次滤波估计值
    k_para->p = (1 - k_para->kg) * k_para->p; //更新测量方差
    
    return (int)k_para->kalman; //返回估计值
}
