static uint8_t const _table_week[12]={0,3,3,6,1,4,6,2,5,0,3,5}; //月修正数据表	
/** 
* @brief  计算星期
* @param  year：年
* @param  month：月
* @param  day：日
* @return  unsigned char：星期
* @note:
*
*/
unsigned char GetWeek(unsigned short year, unsigned char month, unsigned char day)
{
    unsigned short temp;
    unsigned char year_h, year_l;
    year_h = year / 100;
    year_l = year % 100;
    
    if(year_h > 19)
    {
        year_l += 100;
    }
    temp = year_l + year_l / 4;
    temp %= 7;
    temp = temp + day + _table_week[month - 1];
    if(year_l % 4 == 0 && month < 3)
    {
        temp--;
    }
    return (temp % 7);
}
/** 
* @brief  闰年判断
* @param  year：年
* @return  uint8_t：1，闰年；0，平年
* @note:
*
*/
static uint8_t _IsLeapYear(uint16_t year)
{
    if(year % 4 == 0) //必须能被4整除
    {
        if(year % 100 == 0) 
        {
            if(year % 400 == 0)
            {
                return 1;
            }
            else
            {
                return 0;
            }
        }
        else
        {
            return 1;
        }
    }
    else
    {
        return 0;
    }
}
//平年的月份日期表
static const uint8_t _mon_table[12]={31,28,31,30,31,30,31,31,30,31,30,31};
/** 
* @brief  时间戳转RTC时间
* @param  pDate：RTC时间缓存
* @param  rtc_time：时间戳秒数 
* @return  none
* @note:
*
*/
void Seconds2RtcDateFun(RTC_Type *pDate,uint32_t  rtc_time)
{
//    static uint16_t daycnt = 0;
    uint32_t sec = rtc_time;
    uint32_t temp = 0;
    uint16_t base_year = 0, base_month = 0;
    uint32_t sec_temp;
    temp = sec / 86400;

    base_year = 1970;
    while(temp >= 365)
    {
        if(_IsLeapYear(base_year))//闰年
        {
            if(temp >= 366)
            {
                temp -= 366;
            }
            else
            {
//                    base_year++;
                break;
            }
        }
        else
        {
            temp -= 365;
        }
        base_year++;
    }
    pDate->year = base_year;
    
    base_month = 0;
    while(temp >= 28)
    {
        if(_IsLeapYear(base_year) && base_month == 1)
        {
            if(temp >= 29)
            {
                temp -= 29;
            }
            else
            {
                break;
            }
        }
        else
        {
            if(temp >= _mon_table[base_month])
            {
                temp -= _mon_table[base_month];
            }
            else
            {
                break;
            }
        }
        base_month++;
    }
    pDate->month = base_month + 1;
    pDate->day = temp + 1;
        
    sec_temp = sec % 86400;
    pDate->hour = sec_temp / 3600;
    pDate->minute = (sec_temp % 3600) / 60;
    pDate->seconds = (sec_temp % 3600) % 60;
    pDate->week = GetWeek(pDate->year, pDate->month, pDate->day);
}


/** 
* @brief  RTC时间转时间戳
* @param  pDate：RTC时间
* @return  uint32_t：时间戳秒值
* @note:
*
*/
uint32_t RtcDate2SecondsFun(RTC_Type *pDate)
{
    uint16_t t;
	uint32_t sec_count = 0;
    if(pDate->year < 1970 || pDate->year > 2099)
    {
        return 1;	
    }   
    for(t = 1970;t < pDate->year;t++)	//把所有年份的秒钟相加
	{
		if(_IsLeapYear(t))
        {
            sec_count += 31622400;//闰年的秒钟数
        }
		else 
        {
            sec_count += 31536000;//平年的秒钟数
        }
	}
    for(t = 0;t < pDate->month - 1;t++)	   //把前面月份的秒钟数相加
    {
        sec_count += (uint32_t)_mon_table[t] * 86400;//月份秒钟数相加
        if(_IsLeapYear(pDate->year) && t == 1)
        {
            sec_count += 86400;//闰年2月份增加一天的秒钟数	   
        }
    }
    sec_count += (uint32_t)((pDate->day)-1)*86400;//把前面日期的秒钟数相加 
	sec_count += (uint32_t)(pDate->hour)*3600;//小时秒钟数
	sec_count += (uint32_t)(pDate->minute)*60;	 //分钟秒钟数
	sec_count += pDate->seconds ;//最后的秒钟加上去
    
    
    return sec_count;
}
