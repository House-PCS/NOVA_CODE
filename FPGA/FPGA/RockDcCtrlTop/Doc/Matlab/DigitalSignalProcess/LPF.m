% % 定义正弦信号的参数
% A = 1; % 幅度
% f = 10; % 频率 (Hz)
% w = 2 * pi * f; % 角频率 (rad/s)
% p = 0; % 相位 (rad)
% 
% % 定义采样参数
% T = 1; % 信号持续时间 (s)
% fs = 20 * f; % 采样频率 (Hz)
% dt = 1 / fs; % 采样间隔 (s)
% t = -T/2 : dt : T/2; % 时间向量
% 
% % 生成正弦信号
% s = A * sin(w * t + p);
