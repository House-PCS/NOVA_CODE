% 'zoh' - 零阶保持（默认值）。假定控制输入在采样时间周期 Ts 内是分段常量。
% 'foh' - 三角形逼近（修正一阶保持）。假定控制输入在采样时间周期 Ts 内是分段线性值。
% 'impulse' - 冲激不变离散化
% 'tustin' - 双线性（突斯汀）方法。要使用频率预修正指定此方法（以前称为 'prewarp' 方法），请使用 c2dOptions 的 PrewarpFrequency 选项。
% 'matched' - 零极点匹配法
% 'least-squares' - 最小二乘法
% 'damped' - 仅基于 sparss 模型的 TRBDF2 公式的阻尼突斯汀逼近。

%'zoh'、'foh'、'impulse'、'tustin'、'matched'、'least-squares' 或 'damped'。
%%--------------------------------------------------------------------------
% 1. 零阶保持法 (ZOH - Zero Order Hold)
% G(z) = (1 - e^(-wn*T)) / (z - e^(-wn*T))
% y[n] = e^(-wn*T) * y[n-1] + (1 - e^(-wn*T)) * x[n-1]

%%--------------------------------------------------------------------------
%2. 一阶保持法 (FOH - First Order Hold)
%G(z) = (1/T) * Z{ (1 - e^(-sT))/s * G(s)/s }
%y[n] = e^(-wn*T) * y[n-1] + (1 - e^(-wn*T)) * x[n] - e^(-wn*T) * (1 - e^(-wn*T)) * x[n-1]

%%--------------------------------------------------------------------------
%3. 双线性变换法 (Tustin/Bilinear Transform)
%s = (2/T) * (z-1)/(z+1)
%G(z) = wn / [(2/T)*(z-1)/(z+1) + wn] 
%     = (wn*T*(z+1)) / (2(z-1) + wn*T(z+1))
%y[n] = [(2 - wn*T)/(2 + wn*T)] * y[n-1] + [(wn*T)/(2 + wn*T)] * (x[n] + x[n-1])

%%--------------------------------------------------------------------------
%4. 前向差分法 (Forward Euler)
% s = (z-1)/T
% G(z) = wn / [(z-1)/T + wn]
% y[n] = (1 - wn*T) * y[n-1] + wn*T * x[n-1]

%%--------------------------------------------------------------------------
% 5. 后向差分法 (Backward Euler)
% s = (z-1)/(z*T)
% G(z) = wn / [(z-1)/(z*T) + wn]
% y[n] = [1/(1+wn*T)] * y[n-1] + [wn*T/(1+wn*T)] * x[n]

%%--------------------------------------------------------------------------

wn = 6280           ;
fs = 40000
s = tf('s')         ;
sys1 = wn/(s+wn)    ;


Cd = c2d(sys1,1/fs,'zoh')
Cd.Variable = 'z^-1'
Hfoh = c2d(sys1,1/fs,'foh');
Htustin = c2d(sys1,1/fs,'tustin');
Htustin.Variable = 'z^-1'
H = tf(sys1);

step(H,'-',Hfoh,'--');
figure
step(H,'-',Htustin,'--');
bode(sys1);

