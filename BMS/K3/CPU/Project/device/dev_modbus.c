static uint16_t _CrcModbus(uint8_t *p, uint16_t len)
{
    uint8_t ucCRCHi = 0xFF; /* 高CRC字节初始化 */
    uint8_t ucCRCLo = 0xFF; /* 低CRC 字节初始化 */
    uint16_t usIndex;  /* CRC循环中的索引 */
    while (len--)
    {
        usIndex = ucCRCLo ^ *p++; /* 计算CRC */
        ucCRCLo = ucCRCHi ^ _CrcHi[usIndex];
        ucCRCHi = _CrcLo[usIndex];
    }
    return ((uint16_t)ucCRCHi << 8 | ucCRCLo);
}

static bool _CrcJudge(uint8_t *p, uint16_t len)
{
    uint16_t calc_crc, act_crc;

    act_crc = (p[len - 1] << 8) | (p[len - 2]);
    calc_crc = _CrcModbus(p, len - 2);
    if(act_crc == calc_crc)
    {
        return true;
    }
    return false;
}


void ModbusRTUSend(uint8_t *p, uint16_t size)
{
    uint16_t crc;

    Uart1_Fpga_Sofcore_Handle.pTxBuf = p;
    crc = _CrcModbus(p, size);
    Uart1_Fpga_Sofcore_Handle.pTxBuf[size] = crc & 0xFF;
    Uart1_Fpga_Sofcore_Handle.pTxBuf[size + 1] = (crc >> 8) & 0xFF;
    Uart1_Fpga_Sofcore_Handle.tx_size = size + 2;
    _gModbusSendCompleteFlag = 0;
    UartSend(&Uart1_Fpga_Sofcore_Handle);
}

void UART1ToFPGASoftcoreInit()
{
    QueueInit(&gModbusRTURevQueue, MODBUS_RTU_REV_QUEUE_DEPTH, sizeof(ModbusRTURevData_t));
    for(uint8_t i = 0; i < MODBUS_RTU_REV_QUEUE_DEPTH; i++)
    {
        _gModbusData[i].pData = _RevData[i];
    }
    Uart1_Fpga_Sofcore_Handle.pRxBuf = _Uart1RxBuf;
    Uart1_Fpga_Sofcore_Handle.rx_size = MODBUS_RTU_RX_SIZE;
    Uart1_Fpga_Sofcore_Handle.irq_rx_process = _IrqRxProcess;
    Uart1_Fpga_Sofcore_Handle.dma_tx_complete_process = _DMATxCompleteIrqProcess;
    Uart1FpgaSofcoreBspInit();
}

static void _RevDataAnalysis(uint16_t len)
{
    static uint16_t rev_index = 0;
    uint8_t *p = Uart1_Fpga_Sofcore_Handle.pRxBuf;
    if(len < 5)
    {
        return;
    }
    if((*p == REQUST_PACKET_HEAD) && (*(p + 1) == SEND_ADDR) && \
            (*(p + 2) == RECV_ADDR))//私有协议
    {
        if(QueueIsFull(&gModbusRTURevQueue) == true)
        {
            return;//扔掉此包数据
        }
        _gModbusData[rev_index].data_type = TYPE_COM_DATA;
        gBMSSleepFlag = 0;
    }
    else if(MODBUS_DEVICE_ADDR == p[0])//MODBUS协议
    {
        _gModbusData[rev_index].data_type = TYPE_MODBUS_DATA;
        if(_CrcJudge(p, len) == false)
        {
            return;
        }
        gBMSSleepFlag = 0;
    }
    else
    {
        return;
    }
    _gModbusData[rev_index].slave_addr = p[0];
    _gModbusData[rev_index].data_size = len;
    memcpy(_gModbusData[rev_index].pData, p, len);

    if(QueuePut(&gModbusRTURevQueue, &_gModbusData[rev_index]) == false)
    {
        return;
    }
    rev_index++;
    rev_index %= MODBUS_RTU_REV_QUEUE_DEPTH;
}

static void _IrqRxProcess()
{
    uint16_t rev_size = 0;
    /*DMA方式，空闲中断机制*/
    UartDMARxDisable(&Uart1_Fpga_Sofcore_Handle);
    rev_size = UartDMARxDataLength(&Uart1_Fpga_Sofcore_Handle);
    _RevDataAnalysis(rev_size);
    UartDMARxEnable(&Uart1_Fpga_Sofcore_Handle);
}

static void _DMATxCompleteIrqProcess()
{
    _gModbusSendCompleteFlag = 1;
}

static void _DMATxCompleteIrqProcess1()
{
    _gModbusSendCompleteFlag = 1;
}

bool DevModbusSendComplete()
{
    if(_gModbusSendCompleteFlag == 1 && (UartSendCompleteFlag(&Uart1_Fpga_Sofcore_Handle) == true))
    {
        _gModbusSendCompleteFlag = 0;
        return true;
    }
    else
    {
        return false;
    }
}

uint16_t BEBufToUint16(uint8_t *_pBuf)
{
    return (((uint16_t)_pBuf[0] << 8) | _pBuf[1]);
}

void TabLsbToMsb(uint8_t *str, uint16_t len)
{
    for(int j = 0; j < len / 2; j++)
    {
        str[j] ^= str[len - j - 1];
        str[len - j - 1] ^= str[j];
        str[j] ^= str[len - j - 1];
    }
}




